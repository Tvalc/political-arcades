import assert from 'node:assert/strict';
import {KEY,blankCity,award,build,wallet,loadCity,migrateHousing} from '../shared/city-state.mjs';
import {GOAL_KEY,chooseGoal,currentGoal,goalProgress} from '../shared/arcade-catalog.mjs';
import {earnedTotals,earnedSince} from '../shared/city-journey.mjs';
import {capturePacket,parsePacket,applyPacket} from '../shared/save-format.mjs';
const memory=()=>{const data=new Map();return {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,String(v)),removeItem:k=>data.delete(k)};};
const storage=memory(),city=blankCity();city.optedIn=true;
chooseGoal(storage,'court');assert.equal(currentGoal(city,storage),'court');
const before=earnedTotals(city);
for(let i=0;i<3;i++)assert(award(city,{id:'shot-'+i,type:'vote:basket',count:4}));
