assert.deepEqual(earnedSince(city,fractional),[{key:'recreation',count:1.25}]);
chooseGoal(storage,'clinic');const clinic=goalProgress(city,currentGoal(city,storage));assert.equal(clinic.parts.length,2);assert.equal(clinic.ready,false);
assert.equal(chooseGoal(storage,'not-a-project'),false);assert.equal(storage.getItem(GOAL_KEY),'clinic');
const otherBefore=earnedTotals(city);
for(const [type,key]of [['pothole:repair','streets'],['outreach:stop','care'],['crashers:policy','policy'],['crashers:help','care']])assert(award(city,{id:type,type,count:1}));
storage.setItem('pa-housing-city-v1',JSON.stringify({version:1,floors:4}));assert(migrateHousing(city,storage));assert.equal(migrateHousing(city,storage),false);
assert.deepEqual(earnedSince(city,otherBefore),[{key:'housing',count:4},{key:'streets',count:1},{key:'care',count:2},{key:'policy',count:1}]);
storage.setItem(KEY,JSON.stringify(city));const packet=parsePacket(JSON.stringify(capturePacket(storage))),restored=memory();applyPacket(restored,packet);
assert.deepEqual(loadCity(restored),city);assert.equal(currentGoal(loadCity(restored),restored),'clinic');
